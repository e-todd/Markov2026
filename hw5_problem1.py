#Part B:

a=1
b=1
q_0=[1,0,0,0,0]
P = np.array([
    [1-a, a, 0, 0, 0],
    [b/4, 1-a*3/4-b*1/4, a*3/4, 0 ,0],
    [0, b*1/2, 1-a*1/2-b*1/2, a*1/2, 0],
    [0, 0, b*3/4, 1-a*1/4-b*3/4, a*1/4],
    [0, 0, 0, b, 1-b]
])

q_n=np.empty((60, 5))
q_2average=np.empty(60)
steps =np.arange(1,60)
for n in steps:
  P_pow_n = np.linalg.matrix_power(P, n)
  q_Pn= q_0 @ P_pow_n
  q_n[n] = q_Pn
  q_2average[n] = np.average(q_n[0:n, 2])
print(q_n)

