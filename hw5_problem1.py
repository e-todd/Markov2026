#Finding the smallest n where the difference satisfied
steps_long = np.arange(1, 200)
max_difference = np.empty(199)
pi = x
q_n = np.zeros((200, 5))
q_n[0] = q_0

for n in steps_long:
    P_pow_n = np.linalg.matrix_power(P, n)
    q_Pn = q_0 @ P_pow_n
    q_n[n] = q_Pn

for n in steps_long:
    difference_0 = np.abs(q_n[n, 0] - pi[0])
    difference_1 = np.abs(q_n[n, 1] - pi[1])
    difference_2 = np.abs(q_n[n, 2] - pi[2])
    difference_3 = np.abs(q_n[n, 3] - pi[3])
    difference_4 = np.abs(q_n[n, 4] - pi[4])
    max_difference[n-1] = np.max([difference_0, difference_1, difference_2, difference_3, difference_4])
    if max_difference[n-1] < 1e-6:
        print("Smallest n:", n)
        break

#Finding SLEM
eigenvalues = np.linalg.eigvals(P)
eigenvalue_modulus = np.abs(eigenvalues)
eigenvalue_modulus_sorted = np.sort(eigenvalue_modulus)[::-1]
SLEM = eigenvalue_modulus_sorted[1]

print("Eigenvalues:", eigenvalues)
print("Eigenvalue moduli:", eigenvalue_modulus)
