import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import poisson
from scipy.stats import gamma
from scipy.stats import binom

Hours= 2*10**5
lamba = 4

#Simulating by exponential gaps
gaps = np.random.exponential(scale=1/lamba, size=100000000) #scale=mean
arrival_times = np.cumsum(gaps)
arrival_times = arrival_times[arrival_times < Hours]
N_1_exp, edges = np.histogram(arrival_times, bins=np.arange(0, Hours + 1))
print("Exponential method mean:", np.mean(N_1_exp))
print("Exponential method variance:", np.var(N_1_exp))


#Simulating by Poission count then Uniform
N_pois = np.random.poisson(lamba*Hours) #total number Meteors
Unif = np.random.uniform(0, Hours, N_pois) #generates N_pois Uniforms between 0 and Hours
Unif = np.sort(Unif)
N_1_unif, edges = np.histogram( Unif,bins=np.arange(0, Hours + 1))
print("Uniform method mean:", np.mean(N_1_unif))
print("Uniform method variance:", np.var(N_1_unif))


# Theoretical Poisson(4) probabilities
k = np.arange(20) #assume not more than 20 an hour
theory = poisson.pmf(k, mu=4)

plt.hist(N_1_exp, bins=np.arange(-0.5, 15.5, 1), density=True, alpha=0.4, label="Exponential gaps N(1)")
plt.hist(N_1_unif, bins=np.arange(-0.5, 15.5, 1),density=True, alpha=0.4, label="Poisson and Uniform N(1)")
plt.plot(k, theory, label="Poisson(4)", color="black")

plt.xlabel("Number of meteors in one hour, N(1)")
plt.ylabel("Probability")
plt.title("Probability of Number of Meteors in One Hour Across Different Methods")
plt.legend()
plt.show()

