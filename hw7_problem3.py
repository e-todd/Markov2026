t = 1
n_values = np.arange(10, 2001)
delta_t = 1 / n_values

Totalvariation = np.zeros(len(n_values))

for i, n in enumerate(n_values):
    k = np.arange(n + 1)
    binom_probs = binom.pmf(k, n, lamba / n)
    poisson_probs = poisson.pmf(k, lamba)
    Totalvariation[i] = 0.5 * np.sum(np.abs(binom_probs - poisson_probs))

slope, intercept = np.polyfit(np.log(delta_t), np.log(Totalvariation), 1)
print("Estimated slope:", slope)

plt.loglog(delta_t, Totalvariation, '.', label="Total variation distance")

plt.loglog(delta_t, np.exp(intercept) * delta_t**slope, label=f"Fitted log-log slope = {slope:.3f}")

plt.xlabel("Delta t")
plt.ylabel("Total variation distance")
plt.title("Binomial vs. Poisson Distributions")
plt.legend()
plt.show()

