import csv
import numpy as np
import matplotlib.pyplot as plt

"""Download Big 12 conference games for 2025 and 2026 from ESPN's public
scoreboard and write big12.csv. Run from hw6/; rerun after each weekend.
Unplayed games are kept (scores NaN) so they can be predicted.
Standard library only; same output as fetch_big12.m."""
import csv, json, urllib.request

URL = ('https://site.api.espn.com/apis/site/v2/sports/football/college-football/'
       'scoreboard?seasontype=2&groups=4&limit=200')
rows = []
for season in (2025, 2026):
    for w in range(1, 16):
        with urllib.request.urlopen(f'{URL}&dates={season}&week={w}', timeout=30) as f:
            d = json.load(f)
        for ev in d.get('events', []):
            c = ev['competitions'][0]
            cp = c['competitors']
            if not all(str(x['team'].get('conferenceId', '')) == '4' for x in cp):
                continue                                    # Big 12 vs Big 12 only
            H = next(x for x in cp if x['homeAway'] == 'home')
            A = next(x for x in cp if x['homeAway'] == 'away')
            done = int(bool(c['status']['type']['completed']))
            sc = lambda x: int(float(x['score'])) if done else 'NaN'
            row = (season, w, ev['date'][:10], H['team']['location'], sc(H),
                   A['team']['location'], sc(A), int(bool(c['neutralSite'])), done)
            if row not in rows:
                rows.append(row)

with open('big12.csv', 'w', newline='') as f:
    out = csv.writer(f)
    out.writerow(['season', 'week', 'date', 'home', 'home_pts', 'away', 'away_pts',
                  'neutral', 'completed'])
    out.writerows(rows)
n25 = sum(r[0] == 2025 for r in rows)
n26 = sum(r[0] == 2026 and r[8] == 1 for r in rows)
print(f'{len(rows)} games written to big12.csv (2025: {n25}, 2026 played: {n26}, '
      f'2026 to play: {len(rows) - n25 - n26})')

with open("big12.csv") as f:
    games = list(csv.DictReader(f))

teams = sorted(set(g["home"] for g in games) |
               set(g["away"] for g in games))
m = len(teams)
#print(teams)
team_num = {}
for i in range(m):
    team_num[teams[i]] = i

def h(S, T):
    x = (S + 1) / (S + T + 2)
    return 0.5 + 0.5 * np.sign(x - 0.5) * np.sqrt(abs(2*x - 1))

oldgames = [] #2025
currentgames = [] #2026 before 10/10/2026

for g in games:
    if g["completed"] != "1":
        continue
    if g["season"] == "2025":
        oldgames.append(g)
    if (g["season"] == "2026"
            and g["date"] < "2026-10-10"):
        currentgames.append(g)

  #Three Priors:
#Flat Prior
Prior1 = np.full((m, m), 0.5)
np.fill_diagonal(Prior1, 0) #cannot play itself

#Prior from 2025
hvalues= np.zeros((m, m))
count=np.zeros((m, m)) #need prior from (0,1) so need normalized
for g in oldgames:
    i = team_num[g["home"]]
    j = team_num[g["away"]]
    S = int(g["home_pts"])
    T = int(g["away_pts"])
    hvalues[i, j] += h(S, T)
    hvalues[j, i] += h(T, S)
    count[i, j] += 1
    count[j, i] += 1
Prior2=np.full((m, m), 0.5) #if did not play is 1/2
for i in range(m):
    for j in range(m):
        if count[i, j] > 0:
            Prior2[i, j] = hvalues[i, j] / count[i, j]
np.fill_diagonal(Prior2, 0)


# My own prior: stronger team gets 2/3, weaker gets 1/3

Prior3 = np.zeros((m, m))
wins = np.zeros(m)
played = np.zeros(m)

for g in oldgames:
    i = team_num[g["home"]]
    j = team_num[g["away"]]
    S = int(g["home_pts"])
    T = int(g["away_pts"])
    played[i] += 1
    played[j] += 1
    if S > T:
        wins[i] += 1
    elif T > S:
        wins[j] += 1
    else:
        wins[i] += 0.5
        wins[j] += 0.5

for i in range(m):
    for j in range(m):
        if i != j:
            if wins[i] / played[i] > wins[j] / played[j]:
                Prior3[i, j] = 2/3
            elif wins[i] / played[i] < wins[j] / played[j]:
                Prior3[i, j] = 1/3
            else:
                Prior3[i, j] = 1/2

#Computing for 2026
priors = [Prior1, Prior2, Prior3]
names = ["Flat", "2025", "My  prior"]
rankings = []


for k in range(3):
    A = np.zeros((m, m))
    n = np.zeros(m)

    for g in currentgames:
        i = team_num[g["home"]]
        j = team_num[g["away"]]
        S = int(g["home_pts"])
        T = int(g["away_pts"])
        A[i, j] += h(S, T)
        A[j, i] += h(T, S)
        n[i] += 1
        n[j] += 1

    for i in range(m):
        for j in range(m):
            if i != j:
                A[i, j] = (A[i, j] + priors[k][i, j]) / (n[i] + m - 1)

    values, vectors = np.linalg.eig(A)
    order = np.argsort(-np.abs(values))
    lam = values[order[0]].real
    lam2 = values[order[1]]
    r = vectors[:, order[0]].real

    if r.sum() < 0:
        r = -r
    r = r / r.sum()

    rankings.append(r)
    order_teams = np.argsort(-r)

    print("lambda* =", lam)
    print("|lambda2/lambda*| =", abs(lam2 / lam))


    plt.bar([teams[i] for i in order_teams], r[order_teams])
    plt.ylabel("Ranking score")
    plt.title("Big 12 rankings: " + names[k])
    plt.xticks(rotation=75, ha="right")
    plt.show()

# Use the best prior (flat) to predict
r = rankings[2]


for g in games:
    if (g["season"] == "2026"
            and "2026-10-10" <= g["date"] <= "2026-10-11"):
        home = g["home"]
        away = g["away"]
        if r[team_num[home]] > r[team_num[away]]:
            prediction = home
        else:
            prediction = away
        print(g["date"], away, "at", home)
        print("Predicted winner:", prediction)

        if g["completed"] == "1":
            S = int(g["home_pts"])
            T = int(g["away_pts"])
            if S > T:
                actual = home
            elif T > S:
                actual = away
            else:
                actual = "Tie"
            print("Actual winner:", actual)

