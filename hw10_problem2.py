import numpy as np
rng = np.random.default_rng()
import matplotlib.pyplot as plt
from scipy.stats import poisson

T=500
lambda_ = 12
mu = 3

states = np.empty((2, 100000))
t = 0
n = 0

time_in_state = np.zeros(100)

for i, _ in enumerate(states[0]):
    rate = lambda_ + n*mu
    dt = rng.exponential(scale=1/rate)
    time_in_state[n] += min(dt, T-t)
    t += dt

    if t >= T:
        break
    U = rng.uniform(0,1)
    if U < lambda_/rate:
        n += 1
    else:
        n -= 1

    states[:,i] = [n,t]


print(time_in_state[0:18])

state_range=np.arange(0,15)
time_fraction = time_in_state / T
theoretical = poisson.pmf(state_range, 4)


plt.bar(state_range, time_fraction[:15], label="Simulation")
plt.bar(state_range, theoretical, alpha=0.5, label="Poisson(4)")

plt.xlabel("Number of Bikes Out (n)")
plt.ylabel("Fraction of Time")
plt.title("Fraction of Time in Each State")
plt.legend()
plt.show()

largest_difference = np.max(np.abs(time_fraction[:15] - theoretical))
print("Largest difference:", largest_difference)

time_average = np.sum(states * time_fraction[:15])
print("Time average:", time_average)
print("Theoretical rho:", lambda_/mu)

for c in range(100):
    probability = 1 - poisson.cdf(c, 4)

    if probability <= 0.01:
        print("Smallest fleet size:", c)
        print("Probability:", probability)
        break

