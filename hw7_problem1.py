# Functions
def log_g(z):
    alpha, b = z
    beta = np.exp(b)
    n = len(x_data)
    log_likelihood = np.sum(np.log(beta / (beta**2 + (x_data - alpha)**2)))
    return log_likelihood

def run_mcmc(s, T=5*10**4, z0=np.array([0.0, 0.0])):
    chain = np.zeros((T, 2))
    chain[0] = z0
    current_log_g = log_g(z0)
    accepted = 0

    for t in range(1, T):
        xi = np.random.randn(2)
        y = chain[t-1] + s * xi
        prop_log_g = log_g(y)

        log_acc_ratio = prop_log_g - current_log_g
        if np.log(np.random.rand()) < log_acc_ratio:
            chain[t] = y
            current_log_g = prop_log_g
            accepted += 1
        else:
            chain[t] = chain[t-1]

    acc_rate = accepted / (T - 1)
    return chain, acc_rate

def iat(alpha):
    alpha = alpha - np.mean(alpha)
    ac = np.correlate(alpha, alpha, mode="full")
    ac = ac[len(alpha)-1:]
    ac = ac / ac[0]
    total = 1
    for k in range(1, len(alpha)):
        if ac[k] <= 0:
            break
        total += 2 * ac[k]
    return total


