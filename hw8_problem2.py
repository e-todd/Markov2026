import numpy as np
rng = np.random.default_rng()
import matplotlib.pyplot as plt
from scipy.stats import poisson

#Way 1: Emit star and sun photons and keep with probability 0.4

star_values=[]
sun_values=[]
lambda_star=3
lambda_sun=2

for t in range (2*10**5):
    star = np.random.poisson(lambda_star * 5)
    A = rng.random(star)
    star_values.append(np.sum(A < 0.4))

    sun = np.random.poisson(lambda_sun * 5)
    B = rng.random(sun)
    sun_values.append(np.sum(B < 0.4))


#Way 2: Generate directly with those rates
star_values_2=[]
sun_values_2=[]
lambda_star_2=1.2
lambda_sun_2=0.8

for t in range (2*10**5):
    star = np.random.poisson(lambda_star_2 * 5)
    star_values_2.append(star)

    sun = np.random.poisson(lambda_sun_2 * 5)
    sun_values_2.append(sun)

#Comparing the mean and variance:
print("Mean of Star values (1 then 2)")
print(np.mean(star_values))
print(np.mean(star_values_2))

print("Mean of Sun values (1 then 2)")
print(np.mean(sun_values))
print(np.mean(sun_values_2))

print("Variance of Star values (1 then 2)")
print(np.var(star_values))
print(np.var(star_values_2))

print("Variance of Sun values (1 then 2)")
print(np.var(sun_values))
print(np.var(sun_values_2))

#Correlation
correlation = np.corrcoef(star_values, sun_values)[0, 1]
print("Correlation 1:", correlation)

correlation_2 = np.corrcoef(star_values_2, sun_values_2)[0, 1]
print("Correlation 2:", correlation_2)

#Compare the number of detections with Poisson(10)

total_values = np.array(star_values) + np.array(sun_values)
plt.hist(total_values, bins=np.arange(0, 26)-0.5,density=True, label="Simulation Method 1")

total_values_2 = np.array(star_values_2) + np.array(sun_values_2)
plt.hist(total_values_2, bins=np.arange(0, 26)-0.5,density=True, alpha=0.6, label="Simulation Method 2")

x = np.arange(0, 25)
plt.plot(x, poisson.pmf(x, 10), label="Poisson(10)")

plt.xlabel("Total detections")
plt.ylabel("Probability")
plt.title("Comparison of Poisson(10) and Simulation Methods")
plt.legend()
plt.show()

#Among windows with 10 detections get P(exactly 6 star)

windows_with_10 = total_values == 10
prob_6_star = np.mean(np.array(star_values)[windows_with_10] == 6)
print("P(exactly 6 star Method 1| total = 10):", prob_6_star)

windows_with_10_2 = total_values_2 == 10
prob_6_star_2 = np.mean(np.array(star_values_2)[windows_with_10_2] == 6)
print("P(exactly 6 star Method 2 | total = 10):", prob_6_star_2)

#Drawing the first detection type of each kind

n = 2*10**5

T_star = rng.exponential(scale=1/1.2, size=n)
T_sun = rng.exponential(scale=1/0.8, size=n)

M = np.minimum(T_star, T_sun)

# 1 if star arrives first, 0 if sky arrives first
star_first = (T_star < T_sun).astype(int)

# Only consider windows with at least one detection in less than 5 seconds
detected = M <= 5
prob_star_first = np.mean(star_first[detected])
print("P(star first):", prob_star_first)

prob_star_first_1 = np.mean((T_star < T_sun) & (T_star <= 1))
print("P(star first and within 1 second):", prob_star_first_1)

print("E[M]:", np.mean(M))

correlation_time_type = np.corrcoef(M, star_first)[0, 1]

print("Correlation between first detection time and type:", correlation_time_type)

