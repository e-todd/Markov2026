import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import expm
from scipy.optimize import brentq

Q = np.array([
    [-2,  2,  0,  0],
    [ 1, -3,  2,  0],
    [ 0,  2, -4,  2],
    [ 0,  0,  3, -3]
])

x_0 = np.array([1, 0, 0, 0])
pi = np.array([3, 6, 6, 4]) / 19
t_values = np.linspace(0, 5, 501)

x_values = np.array([x_0 @ expm(Q * t) for t in t_values])
TV_values = 0.5 * np.sum(np.abs(x_values - pi), axis=1)


eigenvalues = np.linalg.eigvals(Q)
print("Eigenvalues:", np.sort(eigenvalues))
lambda2 = np.max(eigenvalues.real[eigenvalues.real < -1e-8]) #since lambda1=0
print("Second eigenvalue:", lambda2)

for i in range(4):
    plt.plot(t_values, x_values[:, i], label=f"x{i}(t)")

plt.plot(t_values, TV_values, label="TV(t)")
reference = TV_values[0] * np.exp(lambda2 * t_values)
plt.plot(t_values, reference, "--", label="Slope Lambda 2")

plt.yscale("log")
plt.xlabel("Time (hours)")
plt.ylabel("Probability or TV(t)")
plt.title("Probability Distribution and TV(t) Over Time")
plt.legend()
plt.grid()
plt.show()

def TV(t):
    x = x_0 @ expm(Q * t)
    return 0.5 * np.sum(np.abs(x - pi))
t_001 = brentq(lambda t: TV(t) - 0.01, 0, 5)
print("Time when TV = 0.01:", t_001, "hours")

t_estimate = np.log(100) / abs(lambda2)
print("Theoretical estimate:", t_estimate, "hours")