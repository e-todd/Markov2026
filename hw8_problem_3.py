import numpy as np
rng = np.random.default_rng()
import matplotlib.pyplot as plt
from scipy.optimize import minimize

#Simulate 30 days (720 hours) of arrivals by thinning and report the fraction of proposals kept
T = 720
lambda_max = 20
proposed_times = []
current_time = 0

while current_time < T:
    current_time += rng.exponential(scale=1/lambda_max)
    if current_time < T:
        proposed_times.append(current_time)
proposed_times = np.array(proposed_times)

def true_rate(t):
    return 12 + 8*np.cos(np.pi*(t - 16)/12)
prob_keep = true_rate(proposed_times) / lambda_max

random_numbers = rng.random(len(proposed_times))
keep = random_numbers < prob_keep
arrival_times = proposed_times[keep]

fraction_kept = np.mean(keep)

print("Number of proposals:", len(proposed_times))
print("Number kept:", len(arrival_times))
print("Fraction kept:", fraction_kept)

#Plot the mean number of arrivals in each clock hour (per day) with the true λ(t).

daily_arrivals = [[] for _ in range(30)]

for t in arrival_times:
    day = int(t // 24)
    hour = int(t % 24)
    daily_arrivals[day].append(hour)
hourly_counts = np.zeros((30, 24))

for day in range(30):
    hourly_counts[day] = np.bincount(daily_arrivals[day], minlength=24)

mean_hourly = np.mean(hourly_counts, axis=0)

hours = np.arange(24)
true_rates = true_rate(hours + 0.5)

plt.plot(hours, mean_hourly, 'o-', label="Simulated Mean")
plt.plot(hours, true_rates, 'r-', label="True Rate")
plt.xticks(hours)
plt.xlabel("Clock hour")
plt.ylabel("Mean Arrivals Per Hour")
plt.title("Mean Arrivals Per Hour Per Day")
plt.legend()
plt.show()

# Report the mean and variance over the 30 days of the number of arrivals from 3 to 4 am,and compare with Poisson(4.091)

three_to_four= []

for day in range(30):
    start = day * 24 + 3
    end = day * 24 + 4
    count = np.sum((arrival_times >= start) & (arrival_times < end))
    three_to_four.append(count)

print("Mean:", np.mean(three_to_four))
print("Variance:", np.var(three_to_four))

#Fit λ(t) = a+b cos(π(t−φ)/12)and compare the maximized log-likelihood with that of a constant rate n/T

def log_likelihood(param, times, T):
    a, b, phi = param
    rates = a + b*np.cos(np.pi*(times - phi)/12)
    Lambda = a*T
    loglike = np.sum(np.log(rates)) - Lambda
    return loglike


initial_guess = [10, 5, 14]

result = minimize(
    lambda params: -log_likelihood(params, arrival_times, T),
    initial_guess,
    method='SLSQP',
    bounds=[(0.001, None), (0, None), (0, 24)],
    constraints=[{'type': 'ineq',
                  'fun': lambda params: params[0] - params[1] - 1e-8}]
)

a_hat, b_hat, phi_hat = result.x

print("Estimated a:", a_hat)
print("Estimated b:", b_hat)
print("Estimated phi:", phi_hat)
print("Maximized log-likelihood:", -result.fun)


n = len(arrival_times)
lambda_constant = n/T
log_like_constant = n*np.log(lambda_constant) - lambda_constant*T

print("Constant estimated rate:", lambda_constant)
print("Constant log-likelihood:", log_like_constant)

log_like_fitted = log_likelihood(result.x, arrival_times, T)

print("Fitted log-likelihood:", log_like_fitted)
print("Difference:", log_like_fitted - log_like_constant)